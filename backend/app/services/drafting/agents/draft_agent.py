# ---------------------------------------------------------------------------
# Tier selection matrix — mirrored for party_2 so protective keeps the
# customer/receiving side of the table, not the provider's template.
# ---------------------------------------------------------------------------

_TIER_MATRIX: Dict[tuple[str, str], str] = {
    # Party 1 (drafter / provider / disclosing / company): preferred = most aggressive
    ("party_1", "protective"): "preferred",
    ("party_1", "balanced"): "acceptable",
    ("party_1", "commercial"): "fallback",
    ("party_1", "aggressive"): "fallback",
    # Party 2 (counterparty / customer / receiving / employee): mirror —
    # "protective" for them means the *other* side's aggressive tier flipped,
    # which the playbook encodes as the fallback.
    ("party_2", "protective"): "fallback",
    ("party_2", "balanced"): "acceptable",
    ("party_2", "commercial"): "preferred",
    ("party_2", "aggressive"): "preferred",
}

