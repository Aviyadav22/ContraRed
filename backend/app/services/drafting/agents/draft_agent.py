# ---------------------------------------------------------------------------
# Title map
# ---------------------------------------------------------------------------

_TITLE_MAP: Dict[str, str] = {
    "nda_mutual": "MUTUAL NON-DISCLOSURE AGREEMENT",
    "nda_unilateral": "NON-DISCLOSURE AGREEMENT",
    "saas": "SAAS SUBSCRIPTION AGREEMENT",
    "msa": "MASTER SERVICE AGREEMENT",
    "employment": "EMPLOYMENT AGREEMENT",
}

# ---------------------------------------------------------------------------
# Tier selection matrix — mirrored for party_2 so protective keeps the
# customer/receiving side of the table, not the provider's template.
# ---------------------------------------------------------------------------

_TIER_MATRIX: Dict[tuple[str, str], str] = {
    # Party 1 (drafter / provider / disclosing / company): preferred = most aggressive
    ("party_1", "protective"): "preferred",
    ("party_1", "balanced"): "acceptable",
    ("party_1", "commercial"): "fallback",
    ("party_1", "aggressive"): "fallback",
    # Party 2 (counterparty / customer / receiving / employee): mirror —
    # "protective" for them means the *other* side's aggressive tier flipped,
    # which the playbook encodes as the fallback.
    ("party_2", "protective"): "fallback",
    ("party_2", "balanced"): "acceptable",
    ("party_2", "commercial"): "preferred",
    ("party_2", "aggressive"): "preferred",
}

# How long to give each parallel clause-generation call before timing out.
# Stage-2 (the orchestrator) enforces its own overall timeout; this is a
# per-call cap so a single hang doesn't block the gather.
_PER_CLAUSE_TIMEOUT_S = 90.0

# Cap concurrent Vertex AI calls to avoid hitting per-project rate limits.
_MAX_CONCURRENT_CLAUSES = 10


# ---------------------------------------------------------------------------
# Billing frequency normalisation (frontend sends "annually", backend wants
# "annual"; we tolerate both and any reasonable variant)
# ---------------------------------------------------------------------------

def _normalise_billing_frequency(value: str) -> str:
    v = (value or "").lower().strip()
    if v in {"month", "monthly", "per month"}:
        return "monthly"
    if v in {"quarter", "quarterly", "per quarter"}:
        return "quarterly"
    if v in {"annual", "annually", "yearly", "per year", "year"}:
        return "annual"
    return "monthly"  # safe default


_FREQ_MULTIPLIER: Dict[str, int] = {"monthly": 12, "quarterly": 4, "annual": 1}


class DraftAgent:
    """AI-first drafting agent — builds a RawDraft from a request and playbook."""

    # ------------------------------------------------------------------
    # Tier selection
    # ------------------------------------------------------------------

    @staticmethod
    def _select_tier(
        perspective: str,
        risk_appetite: str,
        clause_category: str | None = None,
        risk_profile: dict[str, str] | None = None,
    ) -> str:
        """Map (perspective, risk_appetite) to a playbook tier name.

        Per-clause override via ``risk_profile`` takes priority when the
        clause_category is present in the profile. Otherwise falls back to
        the global perspective/risk_appetite matrix (which mirrors tiers
        for party_2).
        """
        if risk_profile and clause_category and clause_category in risk_profile:
            override = risk_profile[clause_category].lower()
            return {
                "protective": "preferred",
                "balanced": "acceptable",
                "commercial": "fallback",
                "aggressive": "fallback",
            }.get(override, "acceptable")

        if perspective == "balanced":
            return "acceptable"
        return _TIER_MATRIX.get((perspective, risk_appetite), "acceptable")

    # ------------------------------------------------------------------
    # Context building (not "placeholders" any more — this is the AI's
    # prompt context, which is cleaner than regex substitution)
    # ------------------------------------------------------------------

    @staticmethod
    def _build_context(req: DraftRequest) -> Dict[str, Any]:
        """Build structured context passed into every clause-generation prompt."""
        eff_date = (
            req.effective_date.isoformat()
            if req.effective_date
            else date.today().isoformat()
        )

        ctx: Dict[str, Any] = {
            "contract_type": req.contract_type,
            "effective_date": eff_date,
            "term_months": req.term_months,
            "governing_law": req.governing_law,
            "dispute_resolution": req.dispute_resolution,
            "venue": req.venue or req.governing_law,
            "jurisdiction": req.jurisdiction,
            "perspective": req.drafting_perspective,
            "risk_appetite": req.risk_appetite,
            # Parties
            "party_1": {
                "name": req.party_1.name,
                "short_name": req.party_1.name.split()[0],
                "entity_type": req.party_1.entity_type,
                "jurisdiction": req.party_1.jurisdiction,
                "address": req.party_1.address or None,
            },
            "party_2": {
                "name": req.party_2.name,
                "short_name": req.party_2.name.split()[0],
                "entity_type": req.party_2.entity_type,
                "jurisdiction": req.party_2.jurisdiction,
                "address": req.party_2.address or None,
            },
        }

        # Role aliases (for prompt readability)
        if req.contract_type.startswith("nda"):
            if req.contract_type == "nda_unilateral":
                ctx["roles"] = {
                    "disclosing_party": ctx["party_1"]["name"],
                    "receiving_party": ctx["party_2"]["name"],
                }
        elif req.contract_type == "saas":
            ctx["roles"] = {
                "provider": ctx["party_1"]["name"],
                "customer": ctx["party_2"]["name"],
            }
        elif req.contract_type == "msa":
            ctx["roles"] = {
                "service_provider": ctx["party_1"]["name"],
                "client": ctx["party_2"]["name"],
            }
        elif req.contract_type == "employment":
            ctx["roles"] = {
                "company": ctx["party_1"]["name"],
                "employee": ctx["party_2"]["name"],
            }

        # NDA details
        if req.nda_details:
            ctx["nda"] = {
                "purpose": req.nda_details.purpose,
                "survival_years": req.nda_details.confidentiality_survival_years,
                "non_solicitation": req.nda_details.non_solicitation,
                "non_solicitation_months": req.nda_details.non_solicitation_months or 12,
                "marking_requirement": req.nda_details.marking_requirement,
                "ci_categories": (
                    req.nda_details.ci_categories
                    or [
                        "technical data",
                        "trade secrets",
                        "business plans",
                        "financial information",
                    ]
                ),
            }

        # SaaS details
        if req.saas_details:
            saas = req.saas_details
            bf = _normalise_billing_frequency(saas.billing_frequency)
            multiplier = _FREQ_MULTIPLIER[bf]
            ctx["saas"] = {
                "service_description": saas.service_description,
                "pricing_model": saas.pricing_model,
                "price_amount": saas.price_amount,
                "price_formatted": f"${saas.price_amount:,.2f}",
                "billing_frequency": bf,
                "auto_renewal": saas.auto_renewal,
                "uptime_commitment": saas.uptime_commitment or 99.9,
                "authorized_users": saas.authorized_users,
                "liability_cap_months": saas.liability_cap_months,
                "compliance_frameworks": saas.compliance_frameworks or [],
                "data_regions": saas.data_regions or [],
                "support_tiers": saas.support_tiers or {},
                "annual_value": saas.price_amount * multiplier,
                "annual_value_formatted": f"${saas.price_amount * multiplier:,.2f}",
            }

        # Employment details (fields are optional on DraftRequest)
        if req.contract_type == "employment":
            ctx["employment"] = {
                "title": getattr(req, "employee_title", None),
                "base_salary": getattr(req, "base_salary", None),
                "reporting_manager": getattr(req, "reporting_manager", None),
                "work_location": getattr(req, "work_location", None),
            }

        return ctx

