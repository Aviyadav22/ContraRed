    # ------------------------------------------------------------------
    # Template rendering (fallback only)
    # ------------------------------------------------------------------

    @staticmethod
    def _fill_placeholders(template: str, placeholders: Dict[str, str]) -> str:
        """Replace ``{{key}}`` tokens with values from *placeholders*."""

        def _replacer(match: re.Match) -> str:
            key = match.group(1).strip()
            value = placeholders.get(key, "")
            return value if value else ""

        return re.sub(r"\{\{(\s*\w+\s*)\}\}", _replacer, template)

    # ------------------------------------------------------------------
    # Conditional inclusion
    # ------------------------------------------------------------------

    @staticmethod
    def _should_include(clause: Dict[str, Any], req: DraftRequest) -> bool:
        if clause.get("is_required", True):
            return True

        condition = clause.get("conditional_on")
        if not condition:
            return True

        match = re.match(r"([\w.]+)\s*==\s*(.+)", condition.strip())
        if not match:
            return True

        path_str, expected_raw = match.group(1), match.group(2).strip()

        obj: Any = req
        for part in path_str.split("."):
            obj = getattr(obj, part, None)
            if obj is None:
                return False

        if expected_raw.lower() == "true":
            return bool(obj) is True
        if expected_raw.lower() == "false":
            return bool(obj) is False

        return str(obj) == expected_raw

    # ------------------------------------------------------------------
    # Clause prompt construction
    # ------------------------------------------------------------------

    @staticmethod
    def _build_clause_prompt(
        clause: Dict[str, Any],
        tier_name: str,
        context: Dict[str, Any],
        seed_text: str,
        tier_guidance: str,
    ) -> str:
        """Build the per-clause prompt for Vertex AI."""
        clause_type = clause.get("clause_type", "clause")
        heading = clause.get("section_heading", "")
        drafting_notes = clause.get("drafting_notes", "")
        required_terms = clause.get("required_defined_terms", [])
        cross_refs = clause.get("cross_references", [])

        # Resolve jurisdiction variant (specific first, then country prefix)
        jur = context.get("jurisdiction", "")
        jur_key = jur.split("-")[0] if jur else ""
        jur_variants = clause.get("jurisdiction_variants", {})
        jur_variant = jur_variants.get(jur) or jur_variants.get(jur_key) or ""

        # Map tier → legal posture directive
        tier_directive = {
            "preferred": (
                "Draft this clause in its MOST PROTECTIVE form for the drafting "
                "party. Use firm, assertive language. Narrow exceptions. Short "
                "cure periods. Broad carve-outs. This is the 'open strong' tier."
            ),
            "acceptable": (
                "Draft this clause as a BALANCED, market-standard provision. "
                "Language should be fair to both sides and match what a "
                "reasonable senior associate would produce for an arm's-length "
                "deal. This is the settlement tier."
            ),
            "fallback": (
                "Draft this clause in its COMMERCIAL / COUNTERPARTY-FRIENDLY form. "
                "Softer language ('commercially reasonable efforts'), longer "
                "cure periods, broader exceptions, mutual obligations where "
                "possible. This is the floor — the minimum you'd accept."
            ),
        }.get(tier_name, "Balanced market-standard language.")

        # Perspective directive
        perspective = context.get("perspective", "balanced")
        if perspective == "party_1":
            perspective_note = "The drafting party is Party 1 (the primary party in the preamble)."
        elif perspective == "party_2":
            perspective_note = (
                "The drafting party is Party 2 — the counterparty. Tilt protections "
                "and obligations appropriately so Party 2 has the stronger position."
            )
        else:
            perspective_note = "Draft neutrally, with no party favored."

        # Compact context block
        parties_block = (
            f"- Party 1: {context['party_1']['name']} ({context['party_1']['entity_type']}, "
            f"{context['party_1']['jurisdiction']})\n"
            f"- Party 2: {context['party_2']['name']} ({context['party_2']['entity_type']}, "
            f"{context['party_2']['jurisdiction']})"
        )
        roles = context.get("roles", {})
        roles_block = (
            "\n".join(f"- {k.replace('_', ' ').title()}: {v}" for k, v in roles.items())
            if roles
            else ""
        )

        deal_block = (
            f"- Effective date: {context.get('effective_date', 'TBD')}\n"
            f"- Term: {context.get('term_months', 12)} months\n"
            f"- Governing law: {context.get('governing_law', '(unspecified)')}\n"
            f"- Dispute resolution: {context.get('dispute_resolution', 'arbitration')}\n"
            f"- Venue: {context.get('venue', '(unspecified)')}"
        )

        nda_block = ""
        if "nda" in context:
            n = context["nda"]
            ci_cat_line = ", ".join(n["ci_categories"])
            nda_block = (
                "\nNDA-specific context:\n"
                f"- Purpose of disclosure: {n['purpose']}\n"
                f"- Confidentiality survival: {n['survival_years']} years\n"
                f"- Non-solicitation included: {n['non_solicitation']} "
                f"({n['non_solicitation_months']} months)\n"
                f"- Marking requirement: {n['marking_requirement']}\n"
                f"- Categories of confidential information: {ci_cat_line}"
            )

        employment_block = ""
        employment_clause_directive = ""
        if "employment" in context:
            e = context["employment"]
            employment_block = (
                "\nEmployment-specific context:\n"
                f"- Position / Title: {e.get('title') or '(unspecified)'}\n"
                f"- Base salary: {e.get('base_salary') or '(unspecified)'}\n"
                f"- Reporting manager: {e.get('reporting_manager') or '(unspecified)'}\n"
                f"- Work location: {e.get('work_location') or 'Hybrid'}"
            )
            emp_directives: list[str] = []
            if clause_type in ("position_duties", "preamble") and e.get("title"):
                emp_directives.append(
                    f"MANDATORY: Employee's position / job title is exactly "
                    f"'{e['title']}' — use this verbatim, do not paraphrase."
                )
            if clause_type == "compensation" and e.get("base_salary"):
                emp_directives.append(
                    f"MANDATORY: Base salary must be exactly {e['base_salary']} — "
                    f"do not substitute a placeholder or different amount."
                )
            if clause_type in ("position_duties", "work_hours") and e.get("reporting_manager"):
                emp_directives.append(
                    f"MANDATORY: Employee reports to {e['reporting_manager']}."
                )
            if clause_type == "work_hours" and e.get("work_location"):
                emp_directives.append(
                    f"MANDATORY: Work location arrangement is "
                    f"'{e['work_location']}' — reflect this exactly."
                )
            if emp_directives:
                employment_clause_directive = (
                    "\n\nClause-specific mandates (override tier defaults):\n- "
                    + "\n- ".join(emp_directives)
                )

        saas_block = ""
        saas_clause_directive = ""
        if "saas" in context:
            s = context["saas"]
            frameworks_list = s["compliance_frameworks"]
            frameworks = ", ".join(frameworks_list) or "(none specified)"
            regions_list = s["data_regions"]
            regions = ", ".join(regions_list) or "(not specified)"
            cap_months = s["liability_cap_months"] or "(follow tier standard)"
            support_tiers = s.get("support_tiers") or {}
            support_line = (
                ", ".join(f"{k}: {v}" for k, v in support_tiers.items())
                if support_tiers
                else "(use tier defaults)"
            )
            saas_block = (
                "\nSaaS-specific context:\n"
                f"- Service: {s['service_description']}\n"
                f"- Pricing: {s['price_formatted']} per {s['billing_frequency']} billing period, "
                f"{s['pricing_model']} pricing\n"
                f"- Estimated annual value: {s['annual_value_formatted']}\n"
                f"- Auto-renewal: {s['auto_renewal']}\n"
                f"- Uptime commitment: {s['uptime_commitment']}%\n"
                f"- Authorized users: {s['authorized_users'] or '(unlimited)'}\n"
                f"- Requested liability cap: {cap_months} months of fees\n"
                f"- Compliance frameworks to reference: {frameworks}\n"
                f"- Data processing regions: {regions}\n"
                f"- Customer-specified support tiers: {support_line}"
            )

            # Per-clause directives that force the AI to HONOR the user's SaaS
            # knobs. Without these, generic prompts often ignore the specific
            # numbers/frameworks and fall back to playbook defaults.
            directives: list[str] = []
            if clause_type == "limitation_of_liability" and s.get("liability_cap_months"):
                directives.append(
                    f"MANDATORY: The aggregate liability cap for this clause MUST be "
                    f"exactly {s['liability_cap_months']} months of fees paid by Customer "
                    f"in the {('12 months' if s['liability_cap_months'] >= 12 else f'{s['liability_cap_months']} months')} "
                    f"preceding the claim. Do NOT substitute a different cap. If the tier "
                    f"would normally use a different cap, override it with "
                    f"{s['liability_cap_months']} months of fees."
                )
            if clause_type in ("data_security", "dpa") and frameworks_list:
                directives.append(
                    f"MANDATORY: This clause MUST reference the following compliance "
                    f"frameworks explicitly by name: {', '.join(frameworks_list)}. "
                    f"Provider's security / data-protection obligations must be "
                    f"framed as aligning with these specific frameworks."
                )
            if clause_type in ("data_security", "dpa", "data_ownership") and regions_list:
                directives.append(
                    f"MANDATORY: Reference the following data processing regions "
                    f"explicitly where relevant: {', '.join(regions_list)}. "
                    f"Data shall be processed and stored in these regions."
                )
            if clause_type == "grant_of_license" and s.get("authorized_users"):
                directives.append(
                    f"MANDATORY: The license grant must reference the specific "
                    f"authorized-user cap of {s['authorized_users']} users."
                )
            if clause_type == "sla" and support_tiers:
                tiers_text = "; ".join(f"{k} — {v}" for k, v in support_tiers.items())
                directives.append(
                    f"MANDATORY: The SLA support section must reflect the "
                    f"Customer-specified support tiers exactly: {tiers_text}. "
                    f"Structure the P1/P2/P3/P4 response matrix to match these tier "
                    f"commitments."
                )
            if directives:
                saas_clause_directive = (
                    "\n\nClause-specific mandates (override tier defaults with these):\n- "
                    + "\n- ".join(directives)
                )

        required_terms_block = (
            f"\nRequired defined terms this clause MUST use: {', '.join(required_terms)}"
            if required_terms
            else ""
        )

        jur_block = f"\nJurisdiction note ({jur}): {jur_variant}" if jur_variant else ""

        cross_ref_block = ""
        if cross_refs:
            cross_ref_text = ", ".join(cross_refs)
            cross_ref_block = (
                f"\nThis clause cross-references these other clause types: {cross_ref_text}. "
                "Use the token {{REF:clause_type}} where you would otherwise write "
                "'Section X'. These tokens will be replaced with the real section "
                "numbers after all clauses are generated. Example: "
                "'notwithstanding {{REF:liability}}' or 'as defined in {{REF:definitions}}'."
            )

        seed_block = ""
        if seed_text:
            seed_block = (
                "\n\nReference language from the firm's playbook (use as inspiration, "
                "NOT as a rigid template — you may restructure, tighten, or rewrite "
                "this freely):\n---\n"
                f"{sanitize_for_prompt(seed_text, max_length=3000)}\n---"
            )

        drafting_notes_block = (
            f"\nPlaybook drafting notes: {drafting_notes}" if drafting_notes else ""
        )

        prompt = (
            f"You are a senior contract attorney drafting a single clause of a "
            f"{context['contract_type'].replace('_', ' ').upper()}.\n\n"
            f"Clause to draft: **{heading}** (type: {clause_type})\n\n"
            f"Tier posture: {tier_name.upper()}\n"
            f"{tier_directive}\n\n"
            f"Perspective: {perspective_note}\n\n"
            "Deal context:\n"
            f"{parties_block}\n"
            f"{roles_block}\n"
            f"{deal_block}"
            f"{nda_block}"
            f"{saas_block}"
            f"{saas_clause_directive}"
            f"{employment_block}"
            f"{employment_clause_directive}"
            f"{required_terms_block}"
            f"{jur_block}"
            f"{cross_ref_block}"
            f"{drafting_notes_block}"
            f"{seed_block}\n\n"
            "OUTPUT INSTRUCTIONS (critical):\n"
            "1. Return ONLY the clause body text. No heading. No section "
            "number (those are added by the renderer).\n"
            "2. No markdown formatting. No code fences. No ``` anywhere.\n"
            "3. Do NOT include any preamble like 'Here is the clause' or "
            "'Certainly, below is...'. Start directly with the first word of the clause.\n"
            "4. Use proper legal prose. Defined terms capitalized. Numbered "
            "sub-paragraphs (a), (b), (c) where a clause has multiple parts.\n"
            "5. Length: 2–6 paragraphs, appropriate for this clause type. "
            "Boilerplate sections may be shorter (but at least one full sentence); "
            "substantive sections (liability, indemnification, IP) should be thorough.\n"
            "6. NEVER respond with just a cross-reference like 'Section 3' or a "
            "fragment — always produce the full operative clause text. "
            "Cross-references belong INSIDE the clause body, not as the whole body.\n"
            "7. All dates, names, amounts from the deal context above must be "
            "used verbatim — do not substitute placeholders like [Date] or XXX.\n"
            "8. For cross-references, use {{REF:clause_type}} tokens exactly as "
            "instructed above."
        )

        return prompt

    # ------------------------------------------------------------------
    # Per-clause AI generation
    # ------------------------------------------------------------------

    async def _ai_generate_clause(
        self,
        clause: Dict[str, Any],
        tier_name: str,
        context: Dict[str, Any],
        semaphore: asyncio.Semaphore,
    ) -> Tuple[str, int, bool]:
        """Generate a single clause via Vertex AI. Returns (text, tokens, ai_used)."""
        # Get tier-specific seed + guidance from the playbook (still useful as
        # a knowledge anchor for the AI)
        tier_data = clause.get(tier_name, clause.get("acceptable", {}))
        seed_text = tier_data.get("template_text", "")
        tier_guidance = tier_data.get("guidance", "")

        # Fallback immediately if no Vertex AI
        try:
            from app.core.vertex_client import get_generative_model, is_available
        except ImportError:
            logger.warning("Vertex client unavailable, falling back to seed text")
            return seed_text, 0, False

        if not is_available():
            logger.warning("Vertex AI not configured, falling back to seed text")
            return seed_text, 0, False

        prompt = self._build_clause_prompt(
            clause, tier_name, context, seed_text, tier_guidance
        )

        # Strip markdown fences from AI output
        try:
            from app.services.gemini_analyzer import _strip_markdown_fences
        except ImportError:
            def _strip_markdown_fences(t: str) -> str:
                return t.strip()

        async def _call_vertex(prompt_text: str, attempt: int) -> Tuple[str, int]:
            """Single AI call — returns (text, tokens). Raises on failure."""
            from google.genai.types import GenerateContentConfig
            model = get_generative_model(settings.GEMINI_MODEL)
            response = await asyncio.wait_for(
                model.generate_content_async(
                    [{"role": "user", "parts": [{"text": prompt_text}]}],
                    generation_config=GenerateContentConfig(
                        temperature=0.3 + (0.1 * attempt),  # nudge variety on retry
                        max_output_tokens=3500,
                    ),
                ),
                timeout=_PER_CLAUSE_TIMEOUT_S,
            )
            raw = getattr(response, "text", None) or ""
            cleaned = _strip_markdown_fences(raw).strip()
            tokens = 0
            usage = getattr(response, "usage_metadata", None)
            if usage is not None:
                tokens = getattr(usage, "total_token_count", 0) or 0
            return cleaned, tokens

        # Minimum meaningful clause length — short boilerplate sections like
        # signature blocks can be brief, but anything under this is almost
        # always a bad/truncated AI output.
        MIN_CLAUSE_CHARS = 80

        async with semaphore:
            total_tokens = 0
            for attempt in range(2):  # initial call + 1 retry
                try:
                    text, tokens = await _call_vertex(prompt, attempt)
                    total_tokens += tokens

                    if not text:
                        logger.warning(
                            "Attempt %d: AI returned empty text for clause %s",
                            attempt + 1,
                            clause.get("clause_type"),
                        )
                        continue

                    if len(text) < MIN_CLAUSE_CHARS:
                        logger.warning(
                            "Attempt %d: AI output too short (%d chars) for clause %s: %r",
                            attempt + 1,
                            len(text),
                            clause.get("clause_type"),
                            text[:100],
                        )
                        # Retry with adjusted prompt asking for more detail
                        prompt = prompt + (
                            "\n\nIMPORTANT: Your previous response was too brief. "
                            "Provide the complete clause body text (2-6 paragraphs). "
                            "Do not respond with just a cross-reference or fragment."
                        )
                        continue

                    return text, total_tokens, True

                except asyncio.TimeoutError:
                    logger.warning(
                        "Clause %s timed out on attempt %d after %.0fs",
                        clause.get("clause_type"),
                        attempt + 1,
                        _PER_CLAUSE_TIMEOUT_S,
                    )
                    # Don't retry on timeout — fall through to seed
                    break
                except Exception as e:
                    logger.warning(
                        "Clause %s AI call %d failed (%s)",
                        clause.get("clause_type"),
                        attempt + 1,
                        type(e).__name__,
                    )
                    # Only retry on transient errors, not validation/etc.
                    continue

            logger.warning(
                "Clause %s falling back to seed text after retries",
                clause.get("clause_type"),
            )
            return seed_text, total_tokens, False

    # ------------------------------------------------------------------
    # Cross-reference resolution (post-process)
    # ------------------------------------------------------------------

    @staticmethod
    def _resolve_cross_refs(sections: List[DraftSection]) -> List[DraftSection]:
        """Replace ``{{REF:clause_type}}`` tokens with real section numbers."""
        clause_type_to_number = {
            s.clause_type: s.number for s in sections
        }

        def _replacer(match: re.Match) -> str:
            key = match.group(1).strip()
            num = clause_type_to_number.get(key)
            if num:
                return f"Section {num}"
            # Unresolved reference — fall back to a human-readable form
            pretty = key.replace("_", " ").title()
            return f"Section ({pretty})"

        pattern = re.compile(r"\{\{\s*REF\s*:\s*([\w_]+)\s*\}\}")
        updated: List[DraftSection] = []
        for s in sections:
            new_content = pattern.sub(_replacer, s.content)
            if new_content != s.content:
                updated.append(DraftSection(
                    number=s.number,
                    heading=s.heading,
                    content=new_content,
                    clause_type=s.clause_type,
                    tier_used=s.tier_used,
                    notes=s.notes,
                ))
            else:
                updated.append(s)
        return updated

    # ------------------------------------------------------------------
    # Main generation
    # ------------------------------------------------------------------

    async def generate(
        self,
        req: DraftRequest,
        playbook: Dict[str, Any],
    ) -> RawDraft:
        """Build a full RawDraft from *req* using *playbook* as guidance.

        Each clause generates in parallel via Vertex AI. Section numbers
        are assigned dynamically; cross-references are resolved after
        all clauses complete.
        """
        start = time.monotonic()

        context = self._build_context(req)
        placeholders = self._build_placeholders(req)

        clause_list: List[Dict[str, Any]] = playbook.get("clauses", [])
        # Filter + sort
        clauses_to_generate: List[Tuple[Dict[str, Any], str]] = []
        for clause in sorted(
            clause_list, key=lambda c: c.get("position_in_order", 0)
        ):
            if not self._should_include(clause, req):
                continue
            clause_category = clause.get("category", clause.get("clause_type"))
            tier_name = self._select_tier(
                req.drafting_perspective,
                req.risk_appetite,
                clause_category=clause_category,
                risk_profile=getattr(req, "risk_profile", None) or None,
            )
            clauses_to_generate.append((clause, tier_name))

        logger.info(
            "Generating %d clauses in parallel (concurrency=%d, timeout=%ds/clause)",
            len(clauses_to_generate),
            _MAX_CONCURRENT_CLAUSES,
            int(_PER_CLAUSE_TIMEOUT_S),
        )

        # Parallel generation with concurrency cap
        semaphore = asyncio.Semaphore(_MAX_CONCURRENT_CLAUSES)
        tasks = [
            self._ai_generate_clause(clause, tier, context, semaphore)
            for clause, tier in clauses_to_generate
        ]
        results = await asyncio.gather(*tasks, return_exceptions=True)

        # Build sections
        sections: List[DraftSection] = []
        defined_terms: Dict[str, str] = {}
        tokens_used = 0
        ai_clauses = 0

        for i, ((clause, tier_name), result) in enumerate(
            zip(clauses_to_generate, results), 1
        ):
            # If gather caught an exception, log and fall back to seed
            if isinstance(result, BaseException):
                logger.error(
                    "Unexpected error in clause %s: %s",
                    clause.get("clause_type"),
                    result,
                )
                tier_data = clause.get(tier_name, clause.get("acceptable", {}))
                content = self._fill_placeholders(
                    tier_data.get("template_text", ""), placeholders
                )
                ai_used = False
            else:
                content, tokens, ai_used = result
                tokens_used += tokens
                if ai_used:
                    ai_clauses += 1
                else:
                    # Fill placeholders in the seed fallback
                    content = self._fill_placeholders(content, placeholders)

            sections.append(
                DraftSection(
                    number=str(i),
                    heading=clause.get("section_heading", ""),
                    content=content.strip(),
                    clause_type=clause.get("clause_type", "unknown"),
                    tier_used=tier_name,
                    notes=clause.get("drafting_notes"),
                )
            )

            for term in clause.get("required_defined_terms", []):
                defined_terms.setdefault(term, clause.get("section_heading", ""))

        # Resolve {{REF:clause_type}} tokens
        sections = self._resolve_cross_refs(sections)

        elapsed = time.monotonic() - start
        title = _TITLE_MAP.get(
            req.contract_type,
            req.contract_type.upper().replace("_", " ") + " AGREEMENT",
        )

        logger.info(
            "Draft complete: %d sections (%d AI-generated, %d fallback) in %.1fs, %d tokens",
            len(sections),
            ai_clauses,
            len(sections) - ai_clauses,
            elapsed,
            tokens_used,
        )

        return RawDraft(
            contract_type=req.contract_type,
            title=title,
            sections=sections,
            defined_terms=defined_terms,
            metadata=DraftMetadata(
                playbook_id=playbook.get("contract_type", req.contract_type),
                model=settings.GEMINI_MODEL,
                generation_seconds=round(elapsed, 3),
                tokens_used=tokens_used,
            ),
        )
