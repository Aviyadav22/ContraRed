    # Clause prompt construction
    # ------------------------------------------------------------------

    @staticmethod
    def _build_clause_prompt(
        clause: Dict[str, Any],
        tier_name: str,
        context: Dict[str, Any],
        seed_text: str,
        tier_guidance: str,
    ) -> str:
        """Build the per-clause prompt for Vertex AI."""
        clause_type = clause.get("clause_type", "clause")
        heading = clause.get("section_heading", "")
        drafting_notes = clause.get("drafting_notes", "")
        required_terms = clause.get("required_defined_terms", [])
        cross_refs = clause.get("cross_references", [])

        # Resolve jurisdiction variant (specific first, then country prefix)
        jur = context.get("jurisdiction", "")
        jur_key = jur.split("-")[0] if jur else ""
        jur_variants = clause.get("jurisdiction_variants", {})
        jur_variant = jur_variants.get(jur) or jur_variants.get(jur_key) or ""

        # Map tier → legal posture directive
        tier_directive = {
            "preferred": (
                "Draft this clause in its MOST PROTECTIVE form for the drafting "
                "party. Use firm, assertive language. Narrow exceptions. Short "
                "cure periods. Broad carve-outs. This is the 'open strong' tier."
            ),
            "acceptable": (
                "Draft this clause as a BALANCED, market-standard provision. "
                "Language should be fair to both sides and match what a "
                "reasonable senior associate would produce for an arm's-length "
                "deal. This is the settlement tier."
            ),
            "fallback": (
                "Draft this clause in its COMMERCIAL / COUNTERPARTY-FRIENDLY form. "
                "Softer language ('commercially reasonable efforts'), longer "
                "cure periods, broader exceptions, mutual obligations where "
                "possible. This is the floor — the minimum you'd accept."
            ),
        }.get(tier_name, "Balanced market-standard language.")

        # Perspective directive
        perspective = context.get("perspective", "balanced")
        if perspective == "party_1":
            perspective_note = "The drafting party is Party 1 (the primary party in the preamble)."
        elif perspective == "party_2":
            perspective_note = (
                "The drafting party is Party 2 — the counterparty. Tilt protections "
                "and obligations appropriately so Party 2 has the stronger position."
            )
        else:
            perspective_note = "Draft neutrally, with no party favored."

        # Compact context block
        parties_block = (
            f"- Party 1: {context['party_1']['name']} ({context['party_1']['entity_type']}, "
            f"{context['party_1']['jurisdiction']})\n"
            f"- Party 2: {context['party_2']['name']} ({context['party_2']['entity_type']}, "
            f"{context['party_2']['jurisdiction']})"
        )
        roles = context.get("roles", {})
        roles_block = (
            "\n".join(f"- {k.replace('_', ' ').title()}: {v}" for k, v in roles.items())
            if roles
            else ""
        )

        deal_block = (
            f"- Effective date: {context.get('effective_date', 'TBD')}\n"
            f"- Term: {context.get('term_months', 12)} months\n"
            f"- Governing law: {context.get('governing_law', '(unspecified)')}\n"
            f"- Dispute resolution: {context.get('dispute_resolution', 'arbitration')}\n"
            f"- Venue: {context.get('venue', '(unspecified)')}"
        )

        nda_block = ""
        if "nda" in context:
            n = context["nda"]
            ci_cat_line = ", ".join(n["ci_categories"])
            nda_block = (
                "\nNDA-specific context:\n"
                f"- Purpose of disclosure: {n['purpose']}\n"
                f"- Confidentiality survival: {n['survival_years']} years\n"
                f"- Non-solicitation included: {n['non_solicitation']} "
                f"({n['non_solicitation_months']} months)\n"
                f"- Marking requirement: {n['marking_requirement']}\n"
                f"- Categories of confidential information: {ci_cat_line}"
            )

        employment_block = ""
        employment_clause_directive = ""
        if "employment" in context:
            e = context["employment"]
            employment_block = (
                "\nEmployment-specific context:\n"
                f"- Position / Title: {e.get('title') or '(unspecified)'}\n"
                f"- Base salary: {e.get('base_salary') or '(unspecified)'}\n"
                f"- Reporting manager: {e.get('reporting_manager') or '(unspecified)'}\n"
                f"- Work location: {e.get('work_location') or 'Hybrid'}"
            )
            emp_directives: list[str] = []
            if clause_type in ("position_duties", "preamble") and e.get("title"):
                emp_directives.append(
                    f"MANDATORY: Employee's position / job title is exactly "
                    f"'{e['title']}' — use this verbatim, do not paraphrase."
                )
            if clause_type == "compensation" and e.get("base_salary"):
                emp_directives.append(
                    f"MANDATORY: Base salary must be exactly {e['base_salary']} — "
                    f"do not substitute a placeholder or different amount."
                )
            if clause_type in ("position_duties", "work_hours") and e.get("reporting_manager"):
                emp_directives.append(
                    f"MANDATORY: Employee reports to {e['reporting_manager']}."
                )
            if clause_type == "work_hours" and e.get("work_location"):
                emp_directives.append(
                    f"MANDATORY: Work location arrangement is "
                    f"'{e['work_location']}' — reflect this exactly."
                )
            if emp_directives:
                employment_clause_directive = (
                    "\n\nClause-specific mandates (override tier defaults):\n- "
                    + "\n- ".join(emp_directives)
                )

        # Universal MANDATORY directives — apply to ALL contract types.
        # These force the AI to honor user-selected jurisdiction, governing
        # law, dispute-resolution method, and venue in the clauses where
        # they appear. Without these, the AI echoes Delaware/litigation
        # defaults baked into SaaS seed templates regardless of user input.
        universal_clause_directive = ""
        universal_directives: List[str] = []
        gl_value = context.get("governing_law", "") or ""
        dr_value = context.get("dispute_resolution", "") or ""
        venue_value = context.get("venue", "") or ""
        jurisdiction_value = context.get("jurisdiction", "") or ""

        if clause_type in ("dispute_resolution", "governing_law"):
            if gl_value:
                universal_directives.append(
                    f"MANDATORY: The governing law of this Agreement is "
                    f"exactly '{gl_value}'. Use this phrase verbatim. Do NOT "
                    f"substitute Delaware, California, New York, or any other "
                    f"jurisdiction. The clause must read that the Agreement is "
                    f"governed by the laws of {gl_value}."
                )
            if dr_value:
                # Normalise so the directive reads cleanly
                method = dr_value.lower().strip()
                method_sentence = {
                    "arbitration": (
                        "Disputes MUST be resolved by binding arbitration. "
                        "Do NOT use litigation or court proceedings as the "
                        "primary mechanism. Equitable / injunctive relief may "
                        "still be sought in a court but the substantive "
                        "dispute goes to arbitration."
                    ),
                    "litigation": (
                        "Disputes MUST be resolved by litigation in a court "
                        "of competent jurisdiction. Do NOT default to "
                        "arbitration."
                    ),
                    "mediation": (
                        "Disputes MUST first be escalated to mediation, "
                        "followed by the agreed formal mechanism if unresolved."
                    ),
                }.get(method, (
                    f"Disputes MUST be resolved by {method}. Do NOT substitute "
                    "a different mechanism."
                ))
                universal_directives.append(f"MANDATORY: {method_sentence}")
            if venue_value:
                universal_directives.append(
                    f"MANDATORY: The venue / seat MUST be '{venue_value}'. "
                    f"Do NOT substitute Wilmington, Delaware or any other "
                    f"default."
                )

        # DPA-specific jurisdictional directive (belt-and-suspenders alongside
        # the coherence pass D5).
        if clause_type == "dpa":
            j = jurisdiction_value.upper()
            j_prefix = j.split("-", 1)[0]
            if j_prefix == "IN":
                universal_directives.append(
                    "MANDATORY: This is an India-to-India data processing "
                    "relationship. Write this DPA under the Digital Personal "
                    "Data Protection Act 2023 (DPDP Act). Use DPDP "
                    "terminology: 'Data Fiduciary' = Customer, 'Data "
                    "Processor' = Provider, 'Data Principal' = individual. "
                    "Do NOT reference GDPR, Regulation (EU) 2016/679, the "
                    "EEA, EU Standard Contractual Clauses, or any other "
                    "European instrument — those are the wrong framework for "
                    "this deal."
                )
            elif j_prefix == "EU" or j_prefix in {"DE", "FR", "NL", "IE", "ES", "IT"}:
                universal_directives.append(
                    "MANDATORY: Write this DPA under the EU GDPR (Regulation "
                    "(EU) 2016/679). Use GDPR roles: 'Controller' = "
                    "Customer, 'Processor' = Provider. Reference Article 28 "
                    "requirements. International transfers outside the EEA "
                    "must use the 2021 EU Standard Contractual Clauses."
                )
            elif j == "US-CA":
                universal_directives.append(
                    "MANDATORY: This DPA is for a California deal. Write it "
                    "under the CCPA / CPRA. Use CCPA roles: Customer is the "
                    "'Business', Provider is the 'Service Provider'. Do NOT "
                    "reference GDPR, EEA, or EU-specific instruments."
                )
            elif j_prefix == "GB":
                universal_directives.append(
                    "MANDATORY: Write this DPA under the UK GDPR and Data "
                    "Protection Act 2018. International transfers must use the "
                    "UK International Data Transfer Agreement (IDTA) or the "
                    "UK Addendum to the 2021 EU SCCs."
                )
            elif j_prefix == "SG":
                universal_directives.append(
                    "MANDATORY: Write this DPA under the Singapore Personal "
                    "Data Protection Act (PDPA)."
                )
            elif j_prefix == "AU":
                universal_directives.append(
                    "MANDATORY: Write this DPA under the Australian Privacy "
                    "Act 1988 and the Australian Privacy Principles."
                )
            elif j == "BR":
                universal_directives.append(
                    "MANDATORY: Write this DPA under the Brazilian LGPD "
                    "(Lei Geral de Proteção de Dados)."
                )

        if universal_directives:
            universal_clause_directive = (
                "\n\nJurisdictional mandates (override any conflicting seed "
                "language):\n- "
                + "\n- ".join(universal_directives)
            )

        saas_block = ""
        saas_clause_directive = ""
        if "saas" in context:
            s = context["saas"]
            frameworks_list = s["compliance_frameworks"]
            frameworks = ", ".join(frameworks_list) or "(none specified)"
            regions_list = s["data_regions"]
            regions = ", ".join(regions_list) or "(not specified)"
            cap_months = s["liability_cap_months"] or "(follow tier standard)"
            support_tiers = s.get("support_tiers") or {}
            support_line = (
                ", ".join(f"{k}: {v}" for k, v in support_tiers.items())
                if support_tiers
                else "(use tier defaults)"
            )
            saas_block = (
                "\nSaaS-specific context:\n"
                f"- Service: {s['service_description']}\n"
                f"- Pricing: {s['price_formatted']} per {s['billing_frequency']} billing period, "
                f"{s['pricing_model']} pricing\n"
                f"- Estimated annual value: {s['annual_value_formatted']}\n"
                f"- Auto-renewal: {s['auto_renewal']}\n"
                f"- Uptime commitment: {s['uptime_commitment']}%\n"
                f"- Authorized users: {s['authorized_users'] or '(unlimited)'}\n"
                f"- Requested liability cap: {cap_months} months of fees\n"
                f"- Compliance frameworks to reference: {frameworks}\n"
                f"- Data processing regions: {regions}\n"
                f"- Customer-specified support tiers: {support_line}"
            )

            # Per-clause directives that force the AI to HONOR the user's SaaS
            # knobs. Without these, generic prompts often ignore the specific
            # numbers/frameworks and fall back to playbook defaults.
            directives: list[str] = []
            if clause_type == "limitation_of_liability" and s.get("liability_cap_months"):
                cap_m = s["liability_cap_months"]
                window = "12 months" if cap_m >= 12 else f"{cap_m} months"
                directives.append(
                    f"MANDATORY: The aggregate liability cap for this clause MUST be "
                    f"exactly {cap_m} months of fees paid by Customer "
                    f"in the {window} "
                    f"preceding the claim. Do NOT substitute a different cap. If the tier "
                    f"would normally use a different cap, override it with "
                    f"{cap_m} months of fees."
                )
            if clause_type in ("data_security", "dpa") and frameworks_list:
                directives.append(
                    f"MANDATORY: This clause MUST reference the following compliance "
                    f"frameworks explicitly by name: {', '.join(frameworks_list)}. "
                    f"Provider's security / data-protection obligations must be "
                    f"framed as aligning with these specific frameworks."
                )
            if clause_type in ("data_security", "dpa", "data_ownership") and regions_list:
                directives.append(
                    f"MANDATORY: Reference the following data processing regions "
                    f"explicitly where relevant: {', '.join(regions_list)}. "
                    f"Data shall be processed and stored in these regions."
                )
            if clause_type == "grant_of_license" and s.get("authorized_users"):
                directives.append(
                    f"MANDATORY: The license grant must reference the specific "
                    f"authorized-user cap of {s['authorized_users']} users."
                )
            if clause_type == "sla" and support_tiers:
                tiers_text = "; ".join(f"{k} — {v}" for k, v in support_tiers.items())
                directives.append(
                    f"MANDATORY: The SLA support section must reflect the "
                    f"Customer-specified support tiers exactly: {tiers_text}. "
                    f"Structure the P1/P2/P3/P4 response matrix to match these tier "
                    f"commitments."
                )
            if directives:
                saas_clause_directive = (
                    "\n\nClause-specific mandates (override tier defaults with these):\n- "
                    + "\n- ".join(directives)
                )

        required_terms_block = (
            f"\nRequired defined terms this clause MUST use: {', '.join(required_terms)}"
            if required_terms
            else ""
        )

        jur_block = f"\nJurisdiction note ({jur}): {jur_variant}" if jur_variant else ""

        # Cross-references are handled by NAME, not by section number. This
        # avoids a class of bugs where the AI writes a bare cross-ref token at
        # the start of a clause body ("{{REF:fees}} and is expressly limited...")
        # which then resolves into "Section 6 and is expressly limited..." —
        # a syntactically-valid but content-less orphan opening.
        cross_ref_block = ""
        if cross_refs:
            cross_ref_text = ", ".join(cross_refs)
            cross_ref_block = (
                f"\nThis clause may reference these related clauses when needed: "
                f"{cross_ref_text}. Refer to them by NAME, not by number. Write e.g. "
                f"'the Confidentiality section', 'Exhibit A (Service Level Agreement)', "
                f"'the Indemnification Section', 'this Agreement'. Do NOT write "
                f"'Section 5' or 'Section X'. Do NOT use any curly-brace tokens. "
                f"Cross-references should appear INSIDE the clause body as part of "
                f"a full sentence, never as the opening."
            )

        seed_block = ""
        if seed_text:
            seed_block = (
                "\n\nReference language from the firm's playbook (use as inspiration, "
                "NOT as a rigid template — you may restructure, tighten, or rewrite "
                "this freely):\n---\n"
                f"{sanitize_for_prompt(seed_text, max_length=3000)}\n---"
            )

        drafting_notes_block = (
            f"\nPlaybook drafting notes: {drafting_notes}" if drafting_notes else ""
        )

        # Collect MANDATORY overrides (user-selected knobs) and put them right
        # before the output instructions where the model pays the most attention.
        # Universal directives (governing law, dispute resolution, DPA
        # jurisdiction) go first because they are the highest-risk silent
        # failures — the AI can produce a clean-looking Delaware / GDPR clause
        # that completely ignores the user's selection.
        mandatory_overrides = ""
        for block in (universal_clause_directive, saas_clause_directive, employment_clause_directive):
            if block and "MANDATORY" in block:
                mandatory_overrides += block
        mandatory_overrides_section = (
            f"\n\n=== CRITICAL USER-SPECIFIED OVERRIDES (HIGHEST PRIORITY) ==="
            f"{mandatory_overrides}\n"
            f"These overrides take ABSOLUTE priority over any conflicting guidance in the "
            f"reference seed, tier posture, or playbook notes above. If the seed text "
            f"uses a different value (e.g. a different cap or framework list), you MUST "
            f"override it to honor the user's explicit choice.\n"
            f"==============================================================\n"
        ) if mandatory_overrides else ""

        prompt = (
            f"You are a senior contract attorney drafting a single clause of a "
            f"{context['contract_type'].replace('_', ' ').upper()}.\n\n"
            f"Clause to draft: **{heading}** (type: {clause_type})\n\n"
            f"Tier posture: {tier_name.upper()}\n"
            f"{tier_directive}\n\n"
            f"Perspective: {perspective_note}\n\n"
            "Deal context:\n"
            f"{parties_block}\n"
            f"{roles_block}\n"
            f"{deal_block}"
            f"{nda_block}"
            f"{saas_block}"
            f"{employment_block}"
            f"{required_terms_block}"
            f"{jur_block}"
            f"{cross_ref_block}"
            f"{drafting_notes_block}"
            f"{seed_block}"
            f"{mandatory_overrides_section}"
            "\nOUTPUT INSTRUCTIONS (critical — read carefully):\n"
            "\n"
            "A. WHAT TO RETURN:\n"
            "   - Return ONLY the clause body text. Start directly with the first "
            "word of the operative text. No meta-commentary.\n"
            "   - Do NOT repeat the heading or add a section number. The renderer "
            f"adds '{heading}' as the heading automatically.\n"
            "   - Do NOT start with a numbered or uppercase run-in heading like "
            f"'{heading.upper()}.' or '12. LIMITATION OF LIABILITY.'.\n"
            "   - Do NOT start with 'Section N' or 'Section (X)' — orphan "
            "cross-references as openings are invalid.\n"
            "   - No markdown. No ``` fences. No preamble like 'Here is...'.\n"
            "\n"
            "B. DEFINED-TERM DISCIPLINE (strict):\n"
            "   - Use 'Provider' and 'Customer' (or the equivalent role labels "
            "shown in the roles block above) throughout the clause body. These "
            "are the defined terms for this contract.\n"
            "   - Do NOT use the parties' literal company names in the body of "
            "ordinary clauses. The party names belong ONLY in the Preamble "
            "and Signature Blocks.\n"
            "   - Wrap first-use defined terms in double quotes (e.g. "
            '"Confidential Information"), then use them unquoted afterwards.\n'
            "\n"
            "C. SUB-NUMBERING DISCIPLINE:\n"
            "   - Do NOT prefix sub-paragraphs with numeric labels like '12.1', "
            "'12.2', '14.1'. Those numbers belong to the parent section and the "
            "renderer handles them.\n"
            "   - Use '(a)', '(b)', '(c)' for enumerated sub-parts within a clause. "
            "For deeper nesting use '(i)', '(ii)', '(iii)'.\n"
            "\n"
            "D. CROSS-REFERENCES:\n"
            "   - When referring to another clause in this Agreement, use its "
            "NAME, not a number. Examples of correct references: "
            "'the Confidentiality Section', 'the Data Security obligations', "
            "'Exhibit A (Service Level Agreement)', 'this Agreement', "
            "'the Order Form attached as Exhibit C'.\n"
            "   - Cross-references must appear INSIDE a full sentence, never as "
            "the clause opening.\n"
            "\n"
            "E. SUBSTANCE:\n"
            "   - Length: 2–6 paragraphs as appropriate. Substantive sections "
            "(liability, indemnification, IP, data security) should be thorough "
            "and complete — no stubs. Boilerplate may be shorter but at least one "
            "full operative sentence.\n"
            "   - All dates, names, amounts from the deal context must be used "
            "verbatim — never substitute '[Date]', 'XXX', '[Amount]', etc.\n"
            "   - If a CRITICAL USER-SPECIFIED OVERRIDE block appears above, "
            "those values are non-negotiable — use them verbatim.\n"
        )

        return prompt

    # ------------------------------------------------------------------
    # Per-clause AI generation
    # ------------------------------------------------------------------

    async def _ai_generate_clause(
        self,
        clause: Dict[str, Any],
        tier_name: str,
        context: Dict[str, Any],
        semaphore: asyncio.Semaphore,
    ) -> Tuple[str, int, bool]:
        """Generate a single clause via Vertex AI. Returns (text, tokens, ai_used)."""
        # Get tier-specific seed + guidance from the playbook (still useful as
        # a knowledge anchor for the AI)
        tier_data = clause.get(tier_name, clause.get("acceptable", {}))
        seed_text = tier_data.get("template_text", "")
        tier_guidance = tier_data.get("guidance", "")

        # Fallback immediately if no Vertex AI
        try:
            from app.core.vertex_client import get_generative_model, is_available
        except ImportError:
            logger.warning("Vertex client unavailable, falling back to seed text")
            return seed_text, 0, False

        if not is_available():
            logger.warning("Vertex AI not configured, falling back to seed text")
            return seed_text, 0, False

        prompt = self._build_clause_prompt(
            clause, tier_name, context, seed_text, tier_guidance
        )

        # Strip markdown fences from AI output
        try:
            from app.services.gemini_analyzer import _strip_markdown_fences
        except ImportError:
            def _strip_markdown_fences(t: str) -> str:
                return t.strip()

        async def _call_vertex(prompt_text: str, attempt: int) -> Tuple[str, int]:
            """Single AI call — returns (text, tokens). Raises on failure."""
            from google.genai.types import GenerateContentConfig
            model = get_generative_model(settings.GEMINI_MODEL)
            response = await asyncio.wait_for(
                model.generate_content_async(
                    [{"role": "user", "parts": [{"text": prompt_text}]}],
                    generation_config=GenerateContentConfig(
                        temperature=0.3 + (0.1 * attempt),  # nudge variety on retry
                        max_output_tokens=3500,
                    ),
                ),
                timeout=_PER_CLAUSE_TIMEOUT_S,
            )
            raw = getattr(response, "text", None) or ""
            cleaned = _strip_markdown_fences(raw).strip()
            cleaned = _strip_leading_heading(cleaned, clause.get("section_heading", ""))
            tokens = 0
            usage = getattr(response, "usage_metadata", None)
            if usage is not None:
                tokens = getattr(usage, "total_token_count", 0) or 0
            return cleaned, tokens

        # Minimum meaningful clause length — short boilerplate sections like
        # signature blocks can be brief, but anything under this is almost
        # always a bad/truncated AI output.
        MIN_CLAUSE_CHARS = 80

        async with semaphore:
            total_tokens = 0
            for attempt in range(2):  # initial call + 1 retry
                try:
                    text, tokens = await _call_vertex(prompt, attempt)
                    total_tokens += tokens

                    if not text:
                        logger.warning(
                            "Attempt %d: AI returned empty text for clause %s",
                            attempt + 1,
                            clause.get("clause_type"),
                        )
                        continue

                    if len(text) < MIN_CLAUSE_CHARS:
                        logger.warning(
                            "Attempt %d: AI output too short (%d chars) for clause %s: %r",
                            attempt + 1,
                            len(text),
                            clause.get("clause_type"),
                            text[:100],
                        )
                        # Retry with adjusted prompt asking for more detail
                        prompt = prompt + (
                            "\n\nIMPORTANT: Your previous response was too brief. "
                            "Provide the complete clause body text (2-6 paragraphs). "
                            "Do not respond with just a cross-reference or fragment."
                        )
                        continue

                    return text, total_tokens, True

                except asyncio.TimeoutError:
                    logger.warning(
                        "Clause %s timed out on attempt %d after %.0fs",
                        clause.get("clause_type"),
                        attempt + 1,
                        _PER_CLAUSE_TIMEOUT_S,
                    )
                    # Don't retry on timeout — fall through to seed
                    break
                except Exception as e:
                    logger.warning(
                        "Clause %s AI call %d failed (%s)",
                        clause.get("clause_type"),
                        attempt + 1,
                        type(e).__name__,
                    )
                    # Only retry on transient errors, not validation/etc.
                    continue

            logger.warning(
                "Clause %s falling back to seed text after retries",
                clause.get("clause_type"),
            )
            return seed_text, total_tokens, False

    # ------------------------------------------------------------------
    # Cross-reference resolution (post-process)
    # ------------------------------------------------------------------

    @staticmethod
    def _resolve_cross_refs(sections: List[DraftSection]) -> List[DraftSection]:
        """Replace legacy ``{{REF:clause_type}}`` tokens with named references.

        We no longer instruct the AI to produce these tokens — clauses now
        use named references ('the Confidentiality Section') directly. This
        resolver remains as a safety net in case a playbook seed or an older
        cached output still contains tokens. Resolves to the clause's
        section_heading rather than a bare section number, which reads more
        naturally if a stray token leaks through.
        """
        clause_type_to_heading = {
            s.clause_type: s.heading for s in sections
        }

        def _replacer(match: re.Match) -> str:
            key = match.group(1).strip()
            heading = clause_type_to_heading.get(key)
            if heading:
                return f"the {heading} section"
            pretty = key.replace("_", " ").title()
            return f"the {pretty} section"

        pattern = re.compile(r"\{\{\s*REF\s*:\s*([\w_]+)\s*\}\}")
        updated: List[DraftSection] = []
        for s in sections:
            new_content = pattern.sub(_replacer, s.content)
            if new_content != s.content:
                updated.append(DraftSection(
                    number=s.number,
                    heading=s.heading,
                    content=new_content,
                    clause_type=s.clause_type,
                    tier_used=s.tier_used,
                    notes=s.notes,
                ))
            else:
                updated.append(s)
        return updated

    # ------------------------------------------------------------------
    # Coherence pass (post-generation defect detection + AI repair)
    # ------------------------------------------------------------------

    @staticmethod
    def _detect_defects(
        section: DraftSection,
        context: Dict[str, Any],
    ) -> List[str]:
        """Return a list of human-readable defects in this clause body.

        Empty list means the section is clean. Each string describes a
        specific issue the repair prompt should address.
        """
        text = section.content or ""
        defects: List[str] = []

        # D1: Orphan "Section N" opening (the {{REF:}} resolution artifact).
        # E.g., "Section 22 and is expressly limited..."
        orphan_opener = re.match(
            r"^\s*Section\s*(?:\d+(?:\.\d+)?|\([^)]+\)|[IVX]+)[\s,.]",
            text,
        )
        if orphan_opener:
            defects.append(
                "Clause opens with a bare section reference "
                f"('{text[:60].strip()}...'). Rewrite to start with a full "
                "operative sentence. If the clause needs to refer to another "
                "section, do it by NAME inside a proper sentence."
            )

        # D2: Literal party names instead of role terms.
        # Only flag when MORE than 2 occurrences — a couple in Preamble / SIG
        # are legitimate.
        p1_name = context.get("party_1", {}).get("name", "")
        p2_name = context.get("party_2", {}).get("name", "")
        p1_short = context.get("party_1", {}).get("short_name", "")
        p2_short = context.get("party_2", {}).get("short_name", "")

        # Skip the preamble and signature blocks — names are correct there.
        if section.clause_type not in {"preamble", "signature_blocks", "recitals"}:
            literal_hits = 0
            for name in (p1_name, p2_name, p1_short, p2_short):
                if name and len(name) > 2:
                    literal_hits += len(re.findall(rf"\b{re.escape(name)}\b", text))
            if literal_hits >= 2:
                defects.append(
                    f"Clause uses the parties' literal names "
                    f"('{p1_short}', '{p2_short}') {literal_hits} times in the "
                    "body. Replace with the defined role terms (Provider / "
                    "Customer, or Disclosing Party / Receiving Party, as "
                    "appropriate). Literal names belong only in the Preamble "
                    "and Signature Blocks."
                )

        # D3: Numeric sub-labels that don't match the clause's own section
        # number. E.g., body says "11.1" but clause is actually §12.
        section_num = section.number
        sub_label_match = re.search(r"(?<!\d)(\d{1,2})\.\d+\s+[A-Z]", text)
        if sub_label_match:
            embedded_num = sub_label_match.group(1)
            if embedded_num != section_num:
                defects.append(
                    f"Clause body uses numeric sub-labels ('{embedded_num}.1', "
                    f"'{embedded_num}.2', ...) but this is actually section "
                    f"{section_num}. Replace the numeric sub-labels with "
                    "'(a)', '(b)', '(c)' sub-paragraphs, OR simply drop the "
                    "sub-numbers and let the sub-paragraphs flow as prose."
                )

        # D4: Stub clause. Some sections are expected to be substantive (liability,
        # indemnification, IP, data security, data ownership, SLA) and should
        # be at least 400 chars. Signature/boilerplate OK smaller.
        SUBSTANTIVE_TYPES = {
            "limitation_of_liability",
            "indemnification",
            "intellectual_property",
            "data_security",
            "data_ownership",
            "confidentiality",
            "sla",
            "dpa",
            "representations_warranties",
            "fees_and_payment",
            "term_and_termination",
            "grant_of_license",
            "scope_of_services",
        }
        if section.clause_type in SUBSTANTIVE_TYPES and len(text) < 400:
            defects.append(
                f"Clause is too short for a substantive '{section.clause_type}' "
                f"section ({len(text)} chars). Produce a thorough clause with "
                "2-5 paragraphs of operative language including all the "
                "substantive obligations, carve-outs, and procedures expected "
                "for this clause type."
            )

        # D5: Jurisdiction mismatch in the DPA. If the contract's jurisdiction
        # is India, the DPA must reference DPDP (not GDPR).
        if section.clause_type == "dpa":
            jur = context.get("jurisdiction", "")
            if jur.upper() == "IN" or jur.upper().startswith("IN-"):
                mentions_dpdp = bool(re.search(r"DPDP|Digital Personal Data Protection", text))
                mentions_gdpr = bool(re.search(r"\bGDPR\b|Regulation\s*\(EU\)\s*2016/679|EEA|EU\s*Standard\s*Contractual", text))
                if not mentions_dpdp or mentions_gdpr:
                    defects.append(
                        "Contract jurisdiction is India (IN) so the DPA must be "
                        "written under the Digital Personal Data Protection Act 2023 "
                        "(DPDP Act). Rewrite the DPA to use DPDP terminology "
                        "(Data Fiduciary = Customer, Data Processor = Provider, "
                        "Data Principal = individual). Do NOT reference GDPR, EEA, "
                        "EU SCCs, or EU 2016/679 — these are the wrong framework "
                        "for an India-to-India processing relationship."
                    )

        # D6: Governing law mismatch in the Dispute Resolution clause.
        # The user's requested governing_law must appear in this clause —
        # otherwise the AI has silently substituted Delaware / California
        # defaults from the seed.
        if section.clause_type == "dispute_resolution":
            expected_gl = (context.get("governing_law") or "").strip()
            if expected_gl:
                # Escape regex-unsafe characters in the expected value.
                pattern = re.escape(expected_gl)
                mentions_expected = bool(re.search(pattern, text, re.IGNORECASE))
                # Common wrong defaults the AI might slip into
                WRONG_LAW_DEFAULTS = [
                    r"\bState of Delaware\b",
                    r"\bDelaware\b",
                    r"\bState of California\b",
                    r"\bCalifornia\b",
                    r"\bState of New York\b",
                    r"\bNew York\b",
                ]
                wrong_hits = []
                for wrong_pat in WRONG_LAW_DEFAULTS:
                    # Only flag the wrong default if it ISN'T the expected value
                    # (so "Delaware" is only wrong when expected != Delaware)
                    bare = re.sub(r"\\b|\\s", "", wrong_pat).lower()
                    bare = re.sub(r"state of ", "", bare)
                    if bare not in expected_gl.lower():
                        if re.search(wrong_pat, text):
                            wrong_hits.append(bare)
                if not mentions_expected or wrong_hits:
                    defects.append(
                        f"The user specified '{expected_gl}' as the governing "
                        f"law. The clause must be governed by {expected_gl} "
                        f"and the venue / seat should be a city in "
                        f"{expected_gl}. Do NOT substitute "
                        f"{', '.join(set(wrong_hits)) or 'Delaware or another default US state'}."
                    )

        # D7: Dispute-resolution method mismatch. If user selected
        # "arbitration" but the clause describes "litigation" as the primary
        # mechanism (or vice versa), flag for repair.
        if section.clause_type == "dispute_resolution":
            expected_method = (context.get("dispute_resolution") or "").lower().strip()
            if expected_method:
                # Detect the dominant mechanism actually described in the clause.
                # Look for structural cues — "shall be determined by binding
                # arbitration" vs. "either Party may initiate litigation".
                arb_hits = len(re.findall(r"\b(binding\s+)?arbitration\b", text, re.IGNORECASE))
                lit_hits = len(re.findall(r"\b(?:litigation|initiate\s+(?:an?\s+)?action\s+in\s+(?:the\s+)?courts?|file\s+a\s+lawsuit)\b", text, re.IGNORECASE))
                # "Courts of … jurisdiction" language is ambiguous (could be
                # for equitable relief only), so we look for an emphatic
                # litigation-as-primary signal.
                if expected_method == "arbitration" and lit_hits > arb_hits and arb_hits == 0:
                    defects.append(
                        "User selected ARBITRATION as the dispute-resolution "
                        "mechanism, but the clause describes litigation as the "
                        "primary mechanism. Rewrite so disputes are resolved by "
                        "binding arbitration (the user's choice). Courts may "
                        "still be mentioned for injunctive / equitable relief "
                        "only."
                    )
                elif expected_method == "litigation" and arb_hits > 0 and lit_hits == 0:
                    defects.append(
                        "User selected LITIGATION as the dispute-resolution "
                        "mechanism, but the clause describes binding arbitration. "
                        "Rewrite so disputes are resolved in court."
                    )
                elif expected_method == "mediation" and arb_hits + lit_hits > 0 and not re.search(r"\bmediation\b", text, re.IGNORECASE):
                    defects.append(
                        "User selected MEDIATION as the primary dispute-"
                        "resolution mechanism but the clause does not "
                        "reference mediation. Rewrite to include a mediation "
                        "escalation stage."
                    )

        # D8: Survival list in Effects of Termination must include the key
        # post-termination provisions: Confidentiality (9), Limitation of
        # Liability (13), Dispute Resolution (17). Missing these creates
        # material legal exposure.
        if section.clause_type == "effects_of_termination":
            # Look for an explicit "sections ... shall survive" style list
            survival_match = re.search(
                r"survival|shall\s+survive|survive\s+(?:the\s+)?(?:expiration|termination)",
                text,
                re.IGNORECASE,
            )
            if survival_match:
                # Check that critical clause types are mentioned by name or number
                # (we can't know the exact numbers, so check by keyword).
                confidentiality_ref = bool(re.search(r"confidentialit", text, re.IGNORECASE))
                liability_ref = bool(re.search(r"(limitation\s+of\s+liability|liability\s+cap|limit)", text, re.IGNORECASE))
                dispute_ref = bool(re.search(r"dispute|arbitration|governing\s+law", text, re.IGNORECASE))
                missing = []
                if not confidentiality_ref:
                    missing.append("Confidentiality")
                if not liability_ref:
                    missing.append("Limitation of Liability")
                if not dispute_ref:
                    missing.append("Dispute Resolution / Governing Law")
                if missing:
                    defects.append(
                        "The survival list in this Effects of Termination "
                        f"clause does not reference {', '.join(missing)}. "
                        "Without surviving these sections post-termination, "
                        "the liability cap, confidentiality obligations, and "
                        "dispute mechanism no longer apply — a material legal "
                        "defect. Rewrite to include these sections by name in "
                        "the survival list."
                    )

        return defects

    async def _repair_clause(
        self,
        section: DraftSection,
        defects: List[str],
        context: Dict[str, Any],
    ) -> Optional[str]:
        """Ask Vertex AI to repair a defective clause. Returns new text or None."""
        try:
            from app.core.vertex_client import get_generative_model, is_available
            if not is_available():
                return None
        except ImportError:
            return None

        defect_list = "\n".join(f"- {d}" for d in defects)

        p1 = context.get("party_1", {})
        p2 = context.get("party_2", {})
        roles = context.get("roles", {})
        roles_line = ", ".join(f"{k.replace('_',' ').title()} = {v}"
                               for k, v in roles.items()) or f"Provider = {p1.get('name')}, Customer = {p2.get('name')}"

        prompt = (
            f"You are repairing a defective clause in a {context.get('contract_type','').replace('_',' ').upper()}.\n\n"
            f"Clause heading: **{section.heading}** (type: {section.clause_type})\n"
            f"Jurisdiction: {context.get('jurisdiction', '(unspecified)')}\n"
            f"Defined roles: {roles_line}\n\n"
            f"The current clause body has these defects that MUST be fixed:\n"
            f"{defect_list}\n\n"
            f"Current (defective) clause body:\n---\n{section.content}\n---\n\n"
            "Return ONLY the corrected clause body as prose. No heading, no section "
            "number, no markdown fences, no preamble. Start directly with the first "
            "word of the operative text.\n\n"
            "Rules:\n"
            "- Use the defined role terms (Provider, Customer, etc.) — NOT the "
            "parties' literal company names — throughout the body. Names belong "
            "only in the Preamble / Signature Block.\n"
            "- Use (a), (b), (c) for sub-parts, not '12.1', '12.2'.\n"
            "- Refer to other clauses by NAME ('the Confidentiality Section', "
            "'Exhibit A') never by number ('Section 5').\n"
            "- Never start the body with an orphan 'Section N' reference.\n"
            "- Preserve the substantive legal positions — do not soften or remove "
            "protections, caps, or carve-outs that the current text has.\n"
        )

        try:
            from google.genai.types import GenerateContentConfig
            model = get_generative_model(settings.GEMINI_MODEL)
            response = await asyncio.wait_for(
                model.generate_content_async(
                    [{"role": "user", "parts": [{"text": prompt}]}],
                    generation_config=GenerateContentConfig(
                        temperature=0.2,
                        max_output_tokens=3500,
                    ),
                ),
                timeout=_PER_CLAUSE_TIMEOUT_S,
            )
            raw = getattr(response, "text", None) or ""
            try:
                from app.services.gemini_analyzer import _strip_markdown_fences
            except ImportError:
                def _strip_markdown_fences(t: str) -> str:
                    return t.strip()
            cleaned = _strip_markdown_fences(raw).strip()
            cleaned = _strip_leading_heading(cleaned, section.heading)
            # Reject trivially-short repairs
            if not cleaned or len(cleaned) < 80:
                return None
            return cleaned
        except Exception as e:
            logger.warning(
                "Repair of clause %s failed (%s)",
                section.clause_type,
                type(e).__name__,
            )
            return None

    async def _coherence_pass(
        self,
        sections: List[DraftSection],
        req: DraftRequest,
        context: Dict[str, Any],
    ) -> List[DraftSection]:
        """Detect and repair defects across all sections (in parallel)."""
        # Build list of (index, section, defects) for only defective sections
        flagged: List[Tuple[int, DraftSection, List[str]]] = []
        for i, section in enumerate(sections):
            defects = self._detect_defects(section, context)
            if defects:
                flagged.append((i, section, defects))

        if not flagged:
            logger.info("Coherence pass: 0/%d sections needed repair", len(sections))
            return sections

        logger.info(
            "Coherence pass: %d/%d sections flagged — running repair in parallel",
            len(flagged),
            len(sections),
        )

        # Repair all flagged sections in parallel (bounded by same semaphore)
        semaphore = asyncio.Semaphore(_MAX_CONCURRENT_CLAUSES)

        async def _repair_one(section: DraftSection, defects: List[str]) -> Optional[str]:
            async with semaphore:
                return await self._repair_clause(section, defects, context)

        repair_tasks = [_repair_one(s, d) for (_, s, d) in flagged]
        repairs = await asyncio.gather(*repair_tasks, return_exceptions=True)

        # Apply successful repairs
        repaired_count = 0
        result = list(sections)  # shallow copy
        for (idx, section, defects), repair in zip(flagged, repairs):
            if isinstance(repair, BaseException):
                logger.warning(
                    "Repair exception for %s: %s",
                    section.clause_type,
                    repair,
                )
                continue
            if repair is None:
                logger.info(
                    "Coherence repair for %s unavailable; keeping original",
                    section.clause_type,
                )
                continue
            result[idx] = DraftSection(
                number=section.number,
                heading=section.heading,
                content=repair,
                clause_type=section.clause_type,
                tier_used=section.tier_used,
                notes=section.notes,
            )
            repaired_count += 1
            logger.info(
                "Coherence repaired %s (%d defects)",
                section.clause_type,
                len(defects),
            )

        logger.info(
            "Coherence pass complete: %d/%d sections repaired",
            repaired_count,
            len(flagged),
        )
        return result

