"""
Draft Agent — AI-first
======================
Generates contract clauses via Vertex AI using the playbook as guidance.

Each clause is generated by a separate AI call that receives:
  - Clause type & drafting-tier posture (preferred / acceptable / fallback).
  - Deal context (parties, jurisdiction, term, purpose).
  - Required defined terms the clause must use.
  - Jurisdiction-specific notes when present.
  - The playbook's template text as a *reference seed* (not a rigid output).

All clauses generate in parallel via ``asyncio.gather`` — a 15-clause NDA runs
in ~10–15 s instead of 2+ minutes sequential, eliminating Stage-2 timeouts.

Section numbering is assigned dynamically at render time, so the clause body
never contains hardcoded numbers. Cross-references use ``{{SECTION_REF:type}}``
placeholders that are resolved after all sections are generated.

Failure mode: if an individual clause AI call fails (timeout, rate-limit,
Vertex down), the agent falls back to the filled template text so the draft
always completes. The fallback paths are logged but never throw.
"""

